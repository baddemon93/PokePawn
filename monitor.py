# ── Retailer Health Adaptive Polling ─────────────────────────────────────────

HEALTH_POLL_MIN_SAMPLES = 5

# Reliability -> polling multiplier
#
# >= 95% = healthy
# >= 75% = degraded
# >= 50% = unstable
# <  50% = unhealthy
#
# Neutral observations are excluded from reliability.
HEALTH_POLL_MULTIPLIERS = (
    (95.0, 1.0),
    (75.0, 1.5),
    (50.0, 2.0),
    (0.0, 4.0),
)


def retailer_health_multiplier(retailer: str | None) -> float:
    """
    Return a polling backoff multiplier based on rolling retailer health.

    Neutral observations do not count against reliability.
    Retailers with too few rated samples remain at normal speed.
    """

    if not retailer:
        return 1.0

    retailer_key = normalize_health_retailer(retailer)

    health = get_rolling_health()

    stats = health.get(
        "retailers",
        {},
    ).get(
        retailer_key,
        {},
    )

    successes = int(stats.get("success", 0))
    errors = int(stats.get("errors", 0))

    rated = successes + errors

    # Do not make decisions from tiny sample sizes.
    if rated < HEALTH_POLL_MIN_SAMPLES:
        return 1.0

    reliability = successes / rated * 100

    for threshold, multiplier in HEALTH_POLL_MULTIPLIERS:
        if reliability >= threshold:
            return multiplier

    return 4.0


def retailer_health_snapshot(retailer: str | None) -> tuple[float | None, int, int, int]:
    """
    Return:
        reliability %, success count, neutral count, error count
    """

    if not retailer:
        return None, 0, 0, 0

    retailer_key = normalize_health_retailer(retailer)

    stats = get_rolling_health().get(
        "retailers",
        {},
    ).get(
        retailer_key,
        {},
    )

    successes = int(stats.get("success", 0))
    neutral = int(stats.get("neutral", 0))
    errors = int(stats.get("errors", 0))

    rated = successes + errors

    reliability = (
        successes / rated * 100
        if rated
        else None
    )

    return reliability, successes, neutral, errors


# ── Adaptive Interval ─────────────────────────────────────────────────────────
def adaptive_interval(
    name: str,
    retailer: str | None = None,
) -> float:
    """
    Tier-aware polling with retailer-health backoff.

    Critical windows always retain maximum polling speed:

      BLITZ (3s):      release day ±1 day
      ULTRA_FAST (5s): launch window ±7d
      ULTRA_FAST (5s): surge mode for Tier 1 + Tier 2

    Normal polling is adjusted by retailer reliability:

      >=95%   1.0x
      75-94%  1.5x
      50-74%  2.0x
      <50%    4.0x

    Neutral observations do not reduce retailer health.
    """

    check_surge_expiry()

    tier = get_product_tier(name)

    # --------------------------------------------------------
    # CRITICAL WINDOWS
    #
    # Never slow these down due to retailer health.
    # --------------------------------------------------------

    if is_in_blitz_window(name):
        return BLITZ_INTERVAL

    if is_in_launch_window(name):
        return ULTRA_FAST

    if surge_active and tier <= 2:
        return ULTRA_FAST

    # --------------------------------------------------------
    # NORMAL TIER INTERVAL
    # --------------------------------------------------------

    if tier == 1:
        base = ULTRA_FAST

    elif tier == 2:
        base = FAST_INTERVAL

    else:
        base = BASE_INTERVAL

    # Hot-window prediction tightens Tier 2/3.
    if predict_hot_window(name):
        base = min(base, FAST_INTERVAL)

    # --------------------------------------------------------
    # STALE TIER-3 PRODUCTS
    # --------------------------------------------------------

    if tier == 3:
        events = restock_patterns.get(name, [])

        if events:
            try:
                last_dt = datetime.fromisoformat(events[-1])

                if (
                    datetime.now() - last_dt
                ).days > STALE_DAYS:

                    base = SLOW_INTERVAL

            except Exception:
                pass

        elif not events:
            base = SLOW_INTERVAL

    # --------------------------------------------------------
    # RETAILER HEALTH BACKOFF
    # --------------------------------------------------------

    multiplier = retailer_health_multiplier(retailer)

    adjusted = base * multiplier

    return adjusted


