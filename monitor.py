async def check_target_instore(session, url) -> tuple[bool | None, str, str]:
    if "searchTerm" in url or "/s?" in url:
        return None, "—", "Pre-release stub"

    parts = url.split("-/A-")

    if len(parts) < 2:
        return None, "—", "Bad Target URL"

    tcin = parts[-1].split("?")[0].strip()

    stores = load_local_stores("target")
    location = get_local_location()

    hits = []
    price = "—"
    trustworthy_response = False

    for store in stores:
        store_id = store["id"]

        api = (
            "https://redsky.target.com/redsky_aggregations/v1/web/pdp_client_v1"
            "?key=9f36aeafbe60771e321a7cc95a78140772ab3e96"
            f"&tcin={tcin}"
            f"&store_id={store_id}"
            f"&zip={location.get('zip', '80938')}"
            f"&state={location.get('state', 'CO')}"
            f"&latitude={location.get('latitude', '38.9047')}"
            f"&longitude={location.get('longitude', '-104.6634')}"
        )

        try:
            async with session.get(
                api,
                headers=api_headers("target"),
                timeout=aiohttp.ClientTimeout(total=12),
            ) as r:

                if r.status == 435:
                    return (
                        None,
                        "—",
                        "Target challenge (HTTP 435)",
                    )

                if r.status == 429:
                    return (
                        None,
                        "—",
                        "Target rate limited (HTTP 429)",
                    )

                if r.status != 200:
                    continue

                trustworthy_response = True

                data = await r.json(content_type=None)

                prod = (
                    data
                    .get("data", {})
                    .get("product", {})
                )

                if price == "—":
                    price = (
                        prod
                        .get("price", {})
                        .get("formatted_current_price", "—")
                    )

                store_opts = (
                    prod
                    .get("fulfillment", {})
                    .get("store_options", [])
                )

                for opt in store_opts:
                    try:
                        qty = int(
                            opt.get(
                                "available_to_pick_up_qty",
                                0,
                            ) or 0
                        )
                    except (TypeError, ValueError):
                        qty = 0

                    if qty <= 0:
                        continue

                    option_name = opt.get(
                        "location_name",
                        "",
                    )

                    # Prefer our cached store metadata.
                    hit = {
                        "id": store_id,
                        "name": option_name or store["name"],
                        "address": store.get("address", ""),
                        "qty": qty,
                    }

                    # Avoid duplicate store results.
                    if not any(
                        h["id"] == hit["id"]
                        for h in hits
                    ):
                        hits.append(hit)

        except asyncio.TimeoutError:
            continue

        except aiohttp.ClientError:
            continue

        except Exception:
            continue

    if hits:
        return (
            True,
            price,
            format_local_hits(
                "Target",
                hits,
                "HIGH",
            ),
        )

    if trustworthy_response:
        return False, price, "No local Target stock"

    return None, price, "Target local inventory unavailable"


async def check_walmart_instore(session, url) -> tuple[bool | None, str, str]:
    if "search?q=" in url:
        return None, "—", "Pre-release stub"

    m = re.search(r'/ip/[^/]+/(\d+)', url)

    if not m:
        return None, "—", "Bad Walmart URL"

    item_id = m.group(1)

    stores = load_local_stores("walmart")

    hits = []
    trustworthy_response = False

    for store in stores:
        store_id = store["id"]

        api = (
            "https://www.walmart.com/store/ajax/api/products/availability"
            f"?storeId={store_id}"
            f"&itemIds={item_id}"
        )

        try:
            async with session.get(
                api,
                headers=api_headers("walmart"),
                timeout=aiohttp.ClientTimeout(total=12),
            ) as r:

                if r.status == 429:
                    return (
                        None,
                        "—",
                        "Walmart rate limited",
                    )

                if r.status != 200:
                    continue

                trustworthy_response = True

                data = await r.json(content_type=None)

                items = data.get("items", {})

                item_data = items.get(
                    item_id,
                    items.get(str(item_id), {}),
                )

                status = str(
                    item_data.get(
                        "availabilityStatus",
                        "",
                    )
                ).upper()

                if status != "IN_STOCK":
                    continue

                qty = item_data.get(
                    "availableQuantity"
                )

                try:
                    if qty is not None:
                        qty = int(qty)
                except (TypeError, ValueError):
                    qty = None

                hits.append({
                    "id": store_id,
                    "name": store["name"],
                    "address": store.get(
                        "address",
                        "",
                    ),
                    "qty": qty,
                })

        except asyncio.TimeoutError:
            continue

        except aiohttp.ClientError:
            continue

        except Exception:
            continue

    if hits:
        return (
            True,
            "—",
            format_local_hits(
                "Walmart",
                hits,
                "HIGH",
            ),
        )

    if trustworthy_response:
        return False, "—", "No local Walmart stock"

    return None, "—", "Walmart local inventory unavailable"


async def check_bestbuy_instore(session, url) -> tuple[bool | None, str, str]:
    if "searchpage.jsp" in url:
        return None, "—", "Pre-release stub"

    # Support both classic SKU URLs and newer /sku/1234567 paths.
    sku = None

    patterns = (
        r'/(\d{6,8})\.p(?:[/?]|$)',
        r'/sku/(\d{6,8})',
        r'[?&]skuId=(\d{6,8})',
    )

    for pattern in patterns:
        m = re.search(pattern, url, re.I)

        if m:
            sku = m.group(1)
            break

    if not sku:
        return (
            None,
            "—",
            "Best Buy numeric SKU unavailable",
        )

    stores = load_local_stores("bestbuy")

    if not stores:
        return None, "—", "No Best Buy stores configured"

    store_ids = [
        s["id"]
        for s in stores
    ]

    store_lookup = {
        s["id"]: s
        for s in stores
    }

    sid_str = ",".join(store_ids)

    api = (
        "https://www.bestbuy.com/fulfillment/order/api/storeAvailability"
        f"?skuIds={sku}"
        f"&storeIds={sid_str}"
    )

    try:
        async with session.get(
            api,
            headers=api_headers("bestbuy"),
            timeout=aiohttp.ClientTimeout(total=12),
        ) as r:

            if r.status != 200:
                return (
                    None,
                    "—",
                    f"Best Buy local HTTP {r.status}",
                )

            data = await r.json(content_type=None)

            hits = []

            for sku_data in data.get(
                "skuAvailabilityList",
                [],
            ):
                for result in sku_data.get(
                    "stores",
                    [],
                ):
                    status = str(
                        result.get(
                            "pickupStatus",
                            "",
                        )
                    ).upper()

                    if status not in (
                        "AVAILABLE",
                        "IN_STORE_ONLY",
                        "PICKUP_ONLY",
                    ):
                        continue

                    sid = str(
                        result.get(
                            "storeId",
                            "",
                        )
                    )

                    cached = store_lookup.get(
                        sid,
                        {},
                    )

                    hits.append({
                        "id": sid,
                        "name": result.get(
                            "storeName"
                        ) or cached.get(
                            "name"
                        ) or f"Best Buy #{sid}",
                        "address": cached.get(
                            "address",
                            "",
                        ),
                        "qty": result.get(
                            "availableQuantity"
                        ),
                    })

            if hits:
                return (
                    True,
                    "—",
                    format_local_hits(
                        "Best Buy",
                        hits,
                        "HIGH",
                    ),
                )

            return (
                False,
                "—",
                "No local Best Buy pickup stock",
            )

    except asyncio.TimeoutError:
        return None, "—", "Best Buy local timeout"

    except aiohttp.ClientError as e:
        return (
            None,
            "—",
            f"Best Buy local network error: {type(e).__name__}",
        )

    except Exception as e:
        return (
            None,
            "—",
            f"Best Buy local error: {type(e).__name__}",
        )


async def check_costco_instore(session, url) -> tuple[bool | None, str, str]:
    """
    Conservative Costco warehouse checker.

    IMPORTANT:
      True  = explicit warehouse availability detected
      False = explicit warehouse-unavailable signal detected
      None  = Costco did not provide trustworthy warehouse inventory

    None preserves PokePawn's previous stock state.
    """

    warehouse_ids = load_local_store_ids("costco")

    if not warehouse_ids:
        return None, "—", "No Costco warehouses configured"

    timeout = aiohttp.ClientTimeout(
        total=20,
        connect=7,
        sock_read=15,
    )

    try:
        async with session.get(
            url,
            headers=random_headers("costco"),
            timeout=timeout,
            allow_redirects=True,
        ) as r:

            if r.status != 200:
                return None, "—", f"Costco warehouse HTTP {r.status}"

            text = await r.text(errors="ignore")
            tl = text.lower()

            # --------------------------------------------------------
            # Detect actual challenge/block pages conservatively.
            # Do NOT flag a page merely because security JS mentions
            # captcha/robot somewhere in a normal Costco document.
            # --------------------------------------------------------

            pokemon_signals = (
                "pokemon",
                "pokémon",
                "trading card",
                "tcg",
            )

            challenge_signals = (
                "access denied",
                "verify you are human",
                "please verify",
                "unusual traffic",
                "request blocked",
            )

            has_product_context = any(
                s in tl for s in pokemon_signals
            )

            has_challenge = any(
                s in tl for s in challenge_signals
            )

            if has_challenge and not has_product_context:
                return None, "—", "Costco warehouse challenge"

            # --------------------------------------------------------
            # Price
            # --------------------------------------------------------

            price = "—"

            price_patterns = (
                r'"price"\s*:\s*"?\$?([\d,]+(?:\.\d{1,2})?)',
                r'"currentPrice"\s*:\s*"?\$?([\d,]+(?:\.\d{1,2})?)',
                r'\$\s*([\d,]+\.\d{2})',
            )

            for pattern in price_patterns:
                pm = re.search(pattern, text, re.IGNORECASE)

                if pm:
                    price = f"${pm.group(1).replace(',', '')}"
                    break

            # --------------------------------------------------------
            # Warehouse-specific positive signals
            # --------------------------------------------------------

            positive_signals = (
                "available at your warehouse",
                "in stock at your warehouse",
                "available in warehouse",
                "in-stock at your warehouse",
                "warehouse availability: in stock",
            )

            for signal in positive_signals:
                if signal in tl:
                    return (
                        True,
                        price,
                        "COSTCO WAREHOUSE: availability confirmed",
                    )

            # --------------------------------------------------------
            # Warehouse-specific negative signals
            #
            # These are intentionally strict. Generic Costco.com
            # OUT OF STOCK does NOT prove local warehouse inventory.
            # --------------------------------------------------------

            negative_signals = (
                "out of stock at your warehouse",
                "not available at your warehouse",
                "unavailable at your warehouse",
                "warehouse availability: out of stock",
            )

            for signal in negative_signals:
                if signal in tl:
                    return (
                        False,
                        price,
                        "COSTCO WAREHOUSE: explicitly unavailable",
                    )

            # --------------------------------------------------------
            # CRITICAL:
            #
            # Generic Add to Cart, Out of Stock, online availability,
            # etc. are NOT treated as local warehouse inventory.
            # --------------------------------------------------------

            return (
                None,
                price,
                "Costco warehouse inventory not exposed",
            )

    except asyncio.TimeoutError:
        return None, "—", "Costco warehouse timeout"

    except aiohttp.ClientError as e:
        return (
            None,
            "—",
            f"Costco warehouse network error: {type(e).__name__}",
        )

    except Exception as e:
        return (
            None,
            "—",
            f"Costco warehouse error: {type(e).__name__}",
        )

