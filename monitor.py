async def check_product(session, product: dict):
    name    = product["name"]
    checker = CHECKERS.get(product["retailer"])
    if not checker:
        return

    # Adaptive interval gate
    # Apply rolling retailer-health backoff during normal polling.
    interval = adaptive_interval(
        name,
        product.get("retailer"),
    )

    # Critical release windows intentionally bypass the normal
    # retailer polling floors.
    #
    # BLITZ:       3s
    # Launch:      5s
    # Surge T1/T2: 5s
    critical_window = (
        is_in_blitz_window(name)
        or is_in_launch_window(name)
        or (
            surge_active
            and get_product_tier(name) <= 2
        )
    )

    if not critical_window:
        # Pokemon Center uses additional verification/queue protections.
        # During normal operation, poll it conservatively.
        if product["retailer"] == "pokemon_center":
            interval = max(
                interval,
                random.uniform(60, 75),
            )

        # Best Buy aggressively rejects large concurrent request bursts.
        # During normal operation, retain the Best Buy safety floor.
        if product["retailer"] == "bestbuy":
            interval = max(
                interval,
                random.uniform(20, 30),
            )

    check_intervals[name] = interval

    now = time.time()

    # Retailer-wide circuit breaker.
    retailer = product["retailer"]

    if retailer in ("target", "target_instore"):
        circuit_key = "target"
    elif retailer in ("bestbuy", "bestbuy_instore"):
        circuit_key = "bestbuy"
    elif retailer == "costco":
        circuit_key = "costco"
    elif retailer == "costco_instore":
        circuit_key = "costco_instore"
    elif retailer == "walmart_instore":
        circuit_key = "walmart_instore"
    else:
        circuit_key = None

    if circuit_key:
        circuit_until = retailer_circuit_until.get(circuit_key, 0)

        if now < circuit_until:
            return

        # Circuit expired: allow requests to probe retailer again.
        if circuit_until:
            retailer_circuit_until.pop(circuit_key, None)
            log.info(
                f"🔄 {circuit_key.upper()} CIRCUIT PROBE — monitoring resumed for test request"
            )

    # Honor a temporary retailer failure backoff before making another
    # network request for this product.
    backoff_until = retailer_backoff_until.get(name, 0)

    if now < backoff_until:
        return

    # Expected/neutral inventory responses receive a progressive
    # per-product backoff so we do not repeatedly hammer endpoints
    # that are currently unable to provide usable inventory.
    #
    # Critical release windows intentionally bypass this protection.
    if not critical_window:
        neutral_until = neutral_backoff_until.get(name, 0)

        if now < neutral_until:
            return

        # Expired timer: remove it and allow the product to probe again.
        if neutral_until:
            neutral_backoff_until.pop(name, None)

    if now - last_checked.get(name, 0) < interval:
        return

    last_checked[name] = now

    t0 = time.time()
    try:
        if product["retailer"] in ("bestbuy", "bestbuy_instore"):
            async with BESTBUY_SEMAPHORE:

                # A circuit may have opened while this task was waiting.
                if time.time() < retailer_circuit_until.get("bestbuy", 0):
                    return

                await asyncio.sleep(random.uniform(0.25, 1.25))

                in_stock, price, detail = await checker(
                    session,
                    product["url"],
                )

        elif product["retailer"] in ("target", "target_instore"):
            async with TARGET_SEMAPHORE:

                # A circuit may have opened while this task was waiting.
                if time.time() < retailer_circuit_until.get("target", 0):
                    return

                await asyncio.sleep(random.uniform(0.25, 0.75))

                in_stock, price, detail = await checker(
                    session,
                    product["url"],
                )

        elif product["retailer"] == "walmart_instore":
            async with WALMART_INSTORE_SEMAPHORE:

                # Re-check after waiting in the queue.
                if time.time() < retailer_circuit_until.get(
                    "walmart_instore",
                    0,
                ):
                    return

                await asyncio.sleep(random.uniform(0.15, 0.50))

                in_stock, price, detail = await checker(
                    session,
                    product["url"],
                )

        elif product["retailer"] in ("costco", "costco_instore"):
            async with COSTCO_SEMAPHORE:

                # Costco online and warehouse inventory use independent
                # circuit breakers. A failure in one must not pause the other.
                costco_circuit_key = product["retailer"]

                # Re-check after waiting in the queue.
                if time.time() < retailer_circuit_until.get(
                    costco_circuit_key,
                    0,
                ):
                    return

                await asyncio.sleep(random.uniform(0.25, 0.75))

                in_stock, price, detail = await checker(
                    session,
                    product["url"],
                )

        else:
            in_stock, price, detail = await checker(
                session,
                product["url"],
            )

        # None means the retailer could not give us a trustworthy stock result
        # (for example: CAPTCHA, anti-bot challenge, timeout, or unknown status).
        # Preserve the previous stock state and DO NOT treat it as OOS.
        if in_stock is None:
            n = error_counts.get(name, 0) + 1
            error_counts[name] = n
            cycle_stats[name]["errors"] += 1

            # Telemetry classification happens below after we inspect
            # the retailer detail string.

            # Unknown means UNKNOWN — never convert a timeout, challenge,
            # CAPTCHA, or network failure into an out-of-stock event.
            retry_delay = 0

            if product["retailer"] in ("bestbuy", "bestbuy_instore"):
                retry_delay = BESTBUY_FAILURE_BACKOFF

            elif product["retailer"] in ("target", "target_instore"):
                retry_delay = TARGET_FAILURE_BACKOFF

            if retry_delay:
                retailer_backoff_until[name] = (
                    time.time() + retry_delay
                )

            # ------------------------------------------------------
            # Retailer-wide circuit breaker
            # ------------------------------------------------------
            retailer = product["retailer"]

            # Classify UNKNOWN results before touching circuit health.
            #
            # EXPECTED UNKNOWN:
            #   - pre-release placeholder
            #   - inventory source intentionally unavailable
            #   - unsupported/malformed product configuration
            #
            # These still remain UNKNOWN for stock purposes, but they do
            # not increment or reset retailer circuit counters.
            detail_lower = str(detail).lower()

            expected_unknown = any(
                marker in detail_lower
                for marker in (
                    "pre-release stub",
                    "warehouse inventory not exposed",
                    "bad url",
                    "missing product id",
                    "unsupported inventory",
                )
            )

            # ------------------------------------------------------
            # Costco circuit-health classification
            #
            # The Costco circuit should represent Costco/site health,
            # NOT whether an individual product URL is useful.
            #
            # NEUTRAL:
            #   product HTTP 404
            #   warehouse HTTP 404
            #   availability unknown
            #
            # CIRCUIT FAILURE:
            #   timeout
            #   network error
            #   challenge/block
            #   HTTP 403
            #   HTTP 429
            #   HTTP 5xx
            # ------------------------------------------------------
            costco_circuit_failure = False

            if retailer in ("costco", "costco_instore"):
                if any(
                    marker in detail_lower
                    for marker in (
                        "costco timeout",
                        "warehouse timeout",
                        "network error",
                        "challenge",
                        "rate limited",
                    )
                ):
                    costco_circuit_failure = True

                else:
                    # Only selected HTTP statuses indicate Costco/site
                    # health problems. A product-specific 404 is neutral.
                    http_match = re.search(
                        r"http\s+(\d{3})",
                        detail_lower,
                    )

                    if http_match:
                        status = int(http_match.group(1))

                        costco_circuit_failure = (
                            status in (403, 429)
                            or status >= 500
                        )

            # ------------------------------------------------------
            # Telemetry classification
            # ------------------------------------------------------
            #
            # NEUTRAL means the checker behaved normally but could not
            # provide a meaningful inventory answer. Neutral observations
            # do not reduce retailer reliability.
            #
            neutral_unknown = (
                expected_unknown
                or any(
                    marker in detail_lower
                    for marker in (
                        "costco product http 404",
                        "costco warehouse http 404",
                        "costco availability unknown",
                        "warehouse inventory not exposed",
                        "walmart local inventory unavailable",
                        "pre-release stub",
                        "no costco warehouses configured",
                        "no best buy stores configured",
                        "best buy numeric sku unavailable",
                    )
                )
            )

            record_health_event(
                product["retailer"],
                None if neutral_unknown else False,
                "neutral" if neutral_unknown else "error",
            )

            # ------------------------------------------------------
            # Per-product neutral backoff
            # ------------------------------------------------------
            #
            # Consecutive expected UNKNOWN responses:
            #
            #   1st -> 2 minutes
            #   2nd -> 5 minutes
            #   3rd+ -> 15 minutes
            #
            # A genuine failure breaks the neutral streak and continues
            # through the normal failure/circuit-breaker path below.
            if neutral_unknown:
                neutral_n = neutral_counts.get(name, 0) + 1
                neutral_counts[name] = neutral_n

                if neutral_n == 1:
                    neutral_delay = NEUTRAL_BACKOFF_1

                elif neutral_n == 2:
                    neutral_delay = NEUTRAL_BACKOFF_2

                else:
                    neutral_delay = NEUTRAL_BACKOFF_3

                neutral_backoff_until[name] = (
                    time.time() + neutral_delay
                )

                if neutral_n <= 3 or neutral_n % 10 == 0:
                    log.info(
                        f"⚪ {name}: neutral inventory #{neutral_n} — "
                        f"backing off {neutral_delay}s"
                    )

            else:
                # A real failure breaks the consecutive-neutral streak.
                neutral_counts.pop(name, None)
                neutral_backoff_until.pop(name, None)

            if (
                retailer in ("target", "target_instore")
                and not neutral_unknown
            ):
                # HTTP 435 is an explicit Target anti-bot challenge.
                if "435" in detail or "challenge" in detail.lower():
                    if retailer_circuit_until.get("target", 0) <= time.time():
                        retailer_circuit_until["target"] = (
                            time.time() + TARGET_CIRCUIT_SECONDS
                        )
                        retailer_failure_counts["target"] = 0

                        log.warning(
                            f"🛑 TARGET CIRCUIT OPEN — {detail}; "
                            f"pausing all Target checks for "
                            f"{TARGET_CIRCUIT_SECONDS}s"
                        )

            elif (
                retailer in ("bestbuy", "bestbuy_instore")
                and not neutral_unknown
            ):
                # Best Buy opens only after repeated genuine failures.
                # Neutral inventory results do not affect circuit health.
                bb_failures = retailer_failure_counts.get("bestbuy", 0) + 1
                retailer_failure_counts["bestbuy"] = bb_failures

                if bb_failures >= BESTBUY_CIRCUIT_FAILURES:
                    if retailer_circuit_until.get("bestbuy", 0) <= time.time():
                        retailer_circuit_until["bestbuy"] = (
                            time.time() + BESTBUY_CIRCUIT_SECONDS
                        )

                        log.warning(
                            f"🛑 BESTBUY CIRCUIT OPEN — "
                            f"{bb_failures} consecutive failures; "
                            f"pausing all Best Buy checks for "
                            f"{BESTBUY_CIRCUIT_SECONDS}s"
                        )

            elif (
                retailer in ("costco", "costco_instore")
                and costco_circuit_failure
                and not neutral_unknown
            ):
                # Keep Costco.com and warehouse inventory health independent.
                # Only genuine Costco/site failures increment these counters.
                costco_key = retailer

                costco_failures = (
                    retailer_failure_counts.get(costco_key, 0) + 1
                )
                retailer_failure_counts[costco_key] = costco_failures

                if costco_failures >= COSTCO_CIRCUIT_FAILURES:
                    if retailer_circuit_until.get(costco_key, 0) <= time.time():
                        retailer_circuit_until[costco_key] = (
                            time.time() + COSTCO_CIRCUIT_SECONDS
                        )

                        circuit_label = (
                            "COSTCO ONLINE"
                            if retailer == "costco"
                            else "COSTCO WAREHOUSE"
                        )

                        log.warning(
                            f"🛑 {circuit_label} CIRCUIT OPEN — "
                            f"{costco_failures} consecutive failures; "
                            f"pausing only this Costco channel for "
                            f"{COSTCO_CIRCUIT_SECONDS}s"
                        )

            elif retailer == "walmart_instore" and not neutral_unknown:
                wm_failures = (
                    retailer_failure_counts.get("walmart_instore", 0) + 1
                )
                retailer_failure_counts["walmart_instore"] = wm_failures

                if wm_failures >= WALMART_INSTORE_CIRCUIT_FAILURES:
                    if (
                        retailer_circuit_until.get("walmart_instore", 0)
                        <= time.time()
                    ):
                        retailer_circuit_until["walmart_instore"] = (
                            time.time() + WALMART_INSTORE_CIRCUIT_SECONDS
                        )

                        log.warning(
                            f"🛑 WALMART IN-STORE CIRCUIT OPEN — "
                            f"{wm_failures} consecutive failures; "
                            f"pausing Walmart local checks for "
                            f"{WALMART_INSTORE_CIRCUIT_SECONDS}s"
                        )

            if n <= 3 or n % 20 == 0:
                retry_text = (
                    f" — retry in {retry_delay}s"
                    if retry_delay
                    else ""
                )

                log.warning(
                    f"⏸️  {name}: availability unknown #{n} — "
                    f"{detail}{retry_text}"
                )

            return

        # Best Buy online inventory can briefly flicker ADD_TO_CART.
        # Require two consecutive positive checks before treating it as
        # a confirmed online restock.
        if product["retailer"] == "bestbuy":
            if in_stock and detail in ("ADD_TO_CART", "IN_STOCK", "PRE_ORDER"):
                hits = bestbuy_confirmations.get(name, 0) + 1
                bestbuy_confirmations[name] = hits

                if hits < 2:
                    log.info(
                        f"🔎 Best Buy candidate stock: {name} "
                        f"({hits}/2 confirmation)"
                    )
                    return

                bestbuy_confirmations[name] = 0

            else:
                bestbuy_confirmations[name] = 0

        # A trustworthy response means this product recovered.
        retailer_backoff_until.pop(name, None)

        # Immediately restore normal polling after a trustworthy
        # inventory result.
        if neutral_counts.get(name, 0):
            log.info(
                f"✅ {name}: neutral backoff cleared after "
                f"trustworthy inventory response"
            )

        neutral_counts.pop(name, None)
        neutral_backoff_until.pop(name, None)

        retailer = product["retailer"]

        if retailer in ("target", "target_instore"):
            if retailer_failure_counts.get("target", 0):
                log.info("✅ TARGET CIRCUIT HEALTHY — successful response")
            retailer_failure_counts["target"] = 0
            retailer_circuit_until.pop("target", None)

        elif retailer in ("bestbuy", "bestbuy_instore"):
            if retailer_failure_counts.get("bestbuy", 0):
                log.info("✅ BESTBUY CIRCUIT HEALTHY — successful response")
            retailer_failure_counts["bestbuy"] = 0
            retailer_circuit_until.pop("bestbuy", None)

        elif retailer in ("costco", "costco_instore"):
            # Costco online and warehouse circuits recover independently.
            costco_key = retailer

            if retailer_failure_counts.get(costco_key, 0):
                circuit_label = (
                    "COSTCO ONLINE"
                    if retailer == "costco"
                    else "COSTCO WAREHOUSE"
                )

                log.info(
                    f"✅ {circuit_label} CIRCUIT HEALTHY — successful response"
                )

            retailer_failure_counts[costco_key] = 0
            retailer_circuit_until.pop(costco_key, None)

        elif retailer == "walmart_instore":
            if retailer_failure_counts.get("walmart_instore", 0):
                log.info(
                    "✅ WALMART IN-STORE CIRCUIT HEALTHY — successful response"
                )
            retailer_failure_counts["walmart_instore"] = 0
            retailer_circuit_until.pop("walmart_instore", None)

        elapsed_ms = (time.time() - t0) * 1000
        error_counts[name] = 0
        s = cycle_stats[name]
        s["checks"] += 1

        record_health_event(
            product["retailer"],
            True,
            "success",
        )

        s["avg_ms"] = (
            s["avg_ms"] * (s["checks"] - 1)
            + elapsed_ms
        ) / s["checks"]
    except Exception as e:
        n = error_counts.get(name, 0) + 1
        error_counts[name] = n
        cycle_stats[name]["errors"] += 1

        record_health_event(
            product["retailer"],
            False,
            "exception",
        )

        if n <= 3 or n % 20 == 0:
            log.warning(
                f"⚠️  {name}: error #{n} — "
                f"{type(e).__name__}: {repr(e)}"
            )
        return

    # First observation establishes a silent baseline.
    # This prevents every currently in-stock product from generating
    # a restock alert whenever PokePawn starts.
    first_check = name not in stock_state
    was_in_stock = stock_state.get(name, False)

    tier      = get_product_tier(name)
    predicted = predict_hot_window(name)
    blitz     = is_in_blitz_window(name)

    if first_check:
        stock_state[name] = in_stock
        save_stock_state()

        log.info(
            f"📍 BASELINE: {name} | "
            f"{'IN STOCK' if in_stock else 'OOS'} | {price}"
        )
        return

    # ── RESTOCK ALERT ────────────────────────────────────────────────────────
    if in_stock and not was_in_stock:
        since_last = time.time() - alert_cooldowns.get(name, 0)
        if since_last > COOLDOWN:
            tag = " 🔥 LAUNCH DAY" if blitz else (f" 🏆 T{tier}" if tier <= 2 else "")
            log.info(f"✅ RESTOCK{tag}: {name} | {price} | {detail}")
            alert_cooldowns[name] = time.time()
            restock_times[name]   = time.time()
            record_restock(name, time.time())
            # Tier 1 restock → activate surge
            if tier == 1 and not surge_active:
                activate_surge(name)
            await fire_all_alerts(session, product, price, detail, predicted=predicted)
        else:
            log.debug(f"  Cooldown: {name} ({int(COOLDOWN - since_last)}s left)")

    # ── WENT OOS ─────────────────────────────────────────────────────────────
    elif not in_stock and was_in_stock:
        log.info(f"❌ OOS: {name}")
        oos_times[name] = time.time()

    # ── VELOCITY ALERT (still in stock, but qty dropping fast) ───────────────
    elif in_stock and was_in_stock and "qty=" in detail:
        if track_qty_velocity(name, detail):
            vel_key    = f"velocity:{name}"
            since_vel  = time.time() - alert_cooldowns.get(vel_key, 0)
            if since_vel > COOLDOWN:
                alert_cooldowns[vel_key] = time.time()
                await fire_all_alerts(session, product, price, detail, velocity_alert=True)

    # ── PRICE DROP (confirmed in-stock products only) ─────────────────────────
    #
    # Do not alert on prices returned for sold-out/unavailable products.
    # Retailers such as Costco can expose a valid price even when the item
    # cannot actually be purchased.
    if in_stock is True and price not in ("—", ""):
        is_drop, drop_desc = check_price_drop(name, price)
        if is_drop:
            log.info(f"💸 PRICE DROP: {name} — {drop_desc}")
            await fire_all_alerts(session, product, price, drop_desc, is_price_drop=True)
    else:
        itag = f"⚡{interval}s" if interval <= ULTRA_FAST else f"{interval}s"
        log.debug(f"  {'✅' if in_stock else '⭕'} [{tier_badge(tier)}] {name} [{itag}] {detail}")

    if stock_state.get(name) != in_stock:
        stock_state[name] = in_stock
        save_stock_state()
    else:
        stock_state[name] = in_stock


