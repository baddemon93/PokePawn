async def check_target(session, url) -> tuple[bool, str, str]:
    """
    Target online availability checker.

    Target's RedSky endpoint may return PerimeterX HTTP 435 or time out.
    These conditions are treated as UNKNOWN rather than OUT OF STOCK so
    anti-bot responses cannot create false stock-state transitions.
    """
    if "searchTerm" in url or "/s?" in url:
        return False, "—", "Pre-release stub (not yet listed)"

    parts = url.split("-/A-")
    if len(parts) < 2:
        return False, "—", "Bad URL"

    tcin = parts[-1].split("?")[0].strip()

    # Keep Target requests from firing in one large simultaneous burst.
    await asyncio.sleep(random.uniform(1.0, 3.0))

    zips = [
        ("80901", "CO", "38.83", "-104.82"),
        ("27601", "NC", "35.78", "-78.64"),
        ("10001", "NY", "40.71", "-74.00"),
        ("60601", "IL", "41.88", "-87.63"),
    ]

    zip_code, state, latitude, longitude = random.choice(zips)

    api = (
        "https://redsky.target.com/redsky_aggregations/v1/web/pdp_client_v1"
        "?key=9f36aeafbe60771e321a7cc95a78140772ab3e96"
        f"&tcin={tcin}"
        "&store_id=3991"
        f"&zip={zip_code}"
        f"&state={state}"
        f"&latitude={latitude}"
        f"&longitude={longitude}"
    )

    try:
        async with session.get(
            api,
            headers=api_headers("target"),
            timeout=aiohttp.ClientTimeout(total=18),
        ) as r:

            # PerimeterX / Target anti-bot challenge.
            # IMPORTANT: this is UNKNOWN, not OOS.
            if r.status == 435:
                return None, "—", "Target challenge (HTTP 435)"

            if r.status == 429:
                return None, "—", "Target rate limited (HTTP 429)"

            if r.status != 200:
                return None, "—", f"Target HTTP {r.status}"

            try:
                data = await r.json(content_type=None)
            except Exception:
                return None, "—", "Target invalid response"

            prod = data.get("data", {}).get("product", {})

            if not prod:
                return None, "—", "Target product data unavailable"

            fulfillment = prod.get("fulfillment", {})
            shipping = fulfillment.get("shipping_options", {}) or {}

            avail = shipping.get("availability_status", "")
            price = prod.get("price", {}).get(
                "formatted_current_price",
                "—"
            )

            status = str(avail).upper()

            if status == "IN_STOCK":
                return True, price, "IN_STOCK"

            if status in {
                "OUT_OF_STOCK",
                "UNAVAILABLE",
                "NOT_AVAILABLE",
            }:
                return False, price, status

            # Unknown Target response should never be interpreted as OOS.
            return None, price, status or "Target availability unknown"

    except asyncio.TimeoutError:
        return None, "—", "Target timeout"

    except aiohttp.ClientError as e:
        return None, "—", f"Target network error: {type(e).__name__}"

    except Exception as e:
        return None, "—", f"Target error: {type(e).__name__}"


