LOCAL_STORE_CACHE = Path("data/local_stores.json")



def load_local_stores(retailer: str) -> list[dict]:
    """
    Return complete local-store records.

    Preferred source:
        data/local_stores.json

    Fallback:
        CONFIG["local_stores"]

    Each returned record has at least:
        id
        name
        address
    """

    try:
        if LOCAL_STORE_CACHE.exists():
            data = json.loads(LOCAL_STORE_CACHE.read_text())

            stores = (
                data
                .get("stores", {})
                .get(retailer, [])
            )

            cleaned = []

            for store in stores:
                if isinstance(store, dict):
                    sid = str(store.get("id", "")).strip()

                    if not sid:
                        continue

                    cleaned.append({
                        "id": sid,
                        "name": str(
                            store.get(
                                "name",
                                f"{retailer.title()} #{sid}",
                            )
                        ).strip(),
                        "address": str(
                            store.get("address", "")
                        ).strip(),
                    })

                else:
                    sid = str(store).strip()

                    if sid:
                        cleaned.append({
                            "id": sid,
                            "name": f"{retailer.title()} #{sid}",
                            "address": "",
                        })

            if cleaned:
                return cleaned

    except Exception as e:
        log.warning(
            f"⚠️ Could not load local store details for {retailer}: "
            f"{type(e).__name__}: {e}"
        )

    return [
        {
            "id": str(store_id),
            "name": f"{retailer.title()} #{store_id}",
            "address": "",
        }
        for store_id in CONFIG.get(
            "local_stores",
            {},
        ).get(retailer, [])
    ]


def format_local_hits(
    retailer_label: str,
    hits: list[dict],
    confidence: str = "HIGH",
) -> str:
    """
    Format local inventory hits for logs + Discord.

    Keeps the message compact enough for Discord fields.
    """

    if not hits:
        return "No local stock"

    lines = [
        f"CONFIDENCE: {confidence}",
        f"{retailer_label}: {len(hits)} local store(s)",
    ]

    for hit in hits[:5]:
        name = hit.get("name", "Unknown store")
        address = hit.get("address", "")
        qty = hit.get("qty")

        line = f"• {name}"

        if qty is not None:
            line += f" — qty={qty}"

        if address:
            line += f"\n  {address}"

        lines.append(line)

    if len(hits) > 5:
        lines.append(
            f"• +{len(hits) - 5} more store(s)"
        )

    return "\n".join(lines)


def load_local_store_ids(retailer: str) -> list[str]:
    """
    Return local store IDs for a retailer.

    Priority:
        1. data/local_stores.json generated by store_discovery.py
        2. CONFIG["local_stores"] fallback

    This allows store discovery to improve independently without risking
    the live inventory monitor.
    """

    try:
        if LOCAL_STORE_CACHE.exists():
            data = json.loads(LOCAL_STORE_CACHE.read_text())

            stores = (
                data
                .get("stores", {})
                .get(retailer, [])
            )

            ids = []

            for store in stores:
                if isinstance(store, dict):
                    store_id = store.get("id")
                else:
                    store_id = store

                if store_id is not None:
                    store_id = str(store_id).strip()

                    if store_id:
                        ids.append(store_id)

            if ids:
                return ids

    except Exception as e:
        log.warning(
            f"⚠️ Could not load local store cache for {retailer}: "
            f"{type(e).__name__}: {e}"
        )

    # Safe fallback to the original config.
    return [
        str(store_id)
        for store_id in CONFIG.get("local_stores", {}).get(retailer, [])
    ]


