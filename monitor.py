async def check_bestbuy(session, url) -> tuple[bool | None, str, str]:
    """
    Best Buy availability checker.

    States:
      True  -> confirmed online availability
      False -> confirmed unavailable / sold out / coming soon / in-store only
      None  -> unknown, timeout, blocked, or ambiguous response
    """

    if "searchpage.jsp" in url:
        return False, "—", "PRE_RELEASE_STUB"

    timeout = aiohttp.ClientTimeout(total=18)

    # ------------------------------------------------------------
    # Legacy numeric SKU URLs
    # ------------------------------------------------------------
    sku = None

    m = re.search(r'/(\d{6,8})\.p(?:[/?]|$)', url)
    if m:
        sku = m.group(1)

    if not sku:
        m = re.search(r'[?&]skuId=(\d{6,8})', url, re.I)
        if m:
            sku = m.group(1)

    if not sku:
        m = re.search(r'/sku/(\d{6,8})', url, re.I)
        if m:
            sku = m.group(1)

    if sku:
        api = (
            "https://www.bestbuy.com/api/tcfb/model.json"
            "?paths=%5B%5B%22shop%22%2C%22buttonstate%22%2C%22v5%22%2C"
            f"%22item%22%2C%22skus%22%2C{sku}%5D%5D"
            "&method=post"
        )

        try:
            async with session.get(
                api,
                headers=api_headers("bestbuy"),
                timeout=aiohttp.ClientTimeout(total=12),
            ) as r:

                if r.status == 200:
                    data = await r.json(content_type=None)

                    try:
                        btn = (
                            data["jsonGraph"]["shop"]["buttonstate"]["v5"]
                            ["item"]["skus"][sku]["conditions"]["NONE"]
                            ["destinationZipCode"][""]["buttonState"]["value"]
                        )

                        state = str(btn).upper().replace(" ", "_")

                        if state == "ADD_TO_CART":
                            return True, "—", "ADD_TO_CART"

                        if state in ("SOLD_OUT", "OUT_OF_STOCK", "UNAVAILABLE"):
                            return False, "—", "SOLD_OUT"

                        if state in ("COMING_SOON", "COMINGSOON"):
                            return False, "—", "COMING_SOON"

                        if state in ("IN_STORE_ONLY", "PICKUP_ONLY"):
                            return False, "—", "IN_STORE_ONLY"

                        if state in ("PRE_ORDER", "PREORDER"):
                            if CONFIG.get("skip_preorder", True):
                                return False, "—", "PRE_ORDER"
                            return True, "—", "PRE_ORDER"

                    except (KeyError, TypeError):
                        pass

        except (aiohttp.ClientError, asyncio.TimeoutError):
            pass

    # ------------------------------------------------------------
    # New Best Buy /product/.../JJG... URLs
    # ------------------------------------------------------------
    try:
        async with session.get(
            url,
            headers=random_headers("bestbuy"),
            timeout=timeout,
            allow_redirects=True,
        ) as r:

            if r.status != 200:
                return None, "—", f"Best Buy HTTP {r.status}"

            text = await r.text(errors="ignore")
            tl = text.lower()

            # ----------------------------------------------------
            # Price
            # ----------------------------------------------------
            price = "—"

            price_patterns = (
                r'"currentPrice"\s*:\s*"?\$?([\d,]+(?:\.\d{1,2})?)',
                r'"customerPrice"\s*:\s*"?\$?([\d,]+(?:\.\d{1,2})?)',
                r'"price"\s*:\s*"?\$?([\d,]+(?:\.\d{1,2})?)',
                r'\$\s*([\d,]+\.\d{2})',
            )

            for pattern in price_patterns:
                pm = re.search(pattern, text, re.IGNORECASE)

                if pm:
                    raw = pm.group(1).replace(",", "")

                    try:
                        value = float(raw)

                        # Ignore bogus embedded $0 values.
                        if value > 0:
                            price = f"${value:.2f}"
                            break

                    except ValueError:
                        pass

            # ----------------------------------------------------
            # Strong state signals
            # ----------------------------------------------------

            coming_soon_signals = (
                '"buttonstate":"coming_soon"',
                '"buttonstate":"coming soon"',
                '"buttonstate":"comingsoon"',
                'coming soon',
            )

            in_store_only_signals = (
                '"buttonstate":"in_store_only"',
                '"buttonstate":"in store only"',
                '"buttonstate":"pickup_only"',
                'in store only',
            )

            sold_out_signals = (
                '"buttonstate":"sold_out"',
                '"buttonstate":"sold out"',
                '"buttonstate":"unavailable"',
                '"availability":"https://schema.org/outofstock"',
                '"availability":"outofstock"',
                '"availability":"out_of_stock"',
                'sold out',
                'currently unavailable',
            )

            preorder_signals = (
                '"buttonstate":"pre_order"',
                '"buttonstate":"pre-order"',
                '"buttonstate":"preorder"',
                'data-button-state="pre-order"',
                '>pre-order<',
                '>preorder<',
            )

            add_to_cart_signals = (
                '"buttonstate":"add_to_cart"',
                '"buttonstate":"add to cart"',
                '"buttonstate":"addtocart"',
                'data-button-state="add-to-cart"',
                '>add to cart<',
            )

            # Ordering matters.
            if any(sig in tl for sig in coming_soon_signals):
                return False, price, "COMING_SOON"

            if any(sig in tl for sig in in_store_only_signals):
                return False, price, "IN_STORE_ONLY"

            if any(sig in tl for sig in sold_out_signals):
                return False, price, "SOLD_OUT"

            if any(sig in tl for sig in preorder_signals):
                if CONFIG.get("skip_preorder", True):
                    return False, price, "PRE_ORDER"
                return True, price, "PRE_ORDER"

            if any(sig in tl for sig in add_to_cart_signals):
                return True, price, "ADD_TO_CART"

            if (
                "schema.org/instock" in tl
                or '"availability":"instock"' in tl
                or '"availability":"in_stock"' in tl
            ):
                return True, price, "IN_STOCK"

            # Never call an ambiguous response OOS.
            return None, price, "Best Buy availability unknown"

    except asyncio.TimeoutError:
        return None, "—", "Best Buy timeout"

    except aiohttp.ClientError as e:
        return None, "—", f"Best Buy network error: {type(e).__name__}"


