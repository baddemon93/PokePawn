async def check_costco(session, url) -> tuple[bool | None, str, str]:
    """
    Conservative Costco online availability checker.

    True  = explicit product-level availability detected
    False = explicit product-level sold-out/unavailable detected
    None  = blocked, HTTP error, ambiguous page, or untrusted response

    IMPORTANT:
    Generic Costco page elements such as "add-to-cart" are NOT enough
    to declare a product in stock because Costco pages contain unrelated
    recommendations, navigation data, and embedded application state.
    """

    timeout = aiohttp.ClientTimeout(
        total=20,
        connect=7,
        sock_read=15,
    )

    try:
        async with session.get(
            url,
            headers=random_headers("costco"),
            timeout=timeout,
            allow_redirects=True,
        ) as r:

            if r.status == 404:
                return None, "—", "Costco product HTTP 404"

            if r.status != 200:
                return None, "—", f"Costco HTTP {r.status}"

            text = await r.text(errors="ignore")
            tl = text.lower()

            # ---------------------------------------------------------
            # Validate that Costco actually returned a product page.
            # ---------------------------------------------------------

            product_context = any(
                signal in tl
                for signal in (
                    "pokemon",
                    "pokémon",
                    "trading card",
                    "tcg",
                )
            )

            challenge = any(
                signal in tl
                for signal in (
                    "access denied",
                    "verify you are human",
                    "please verify",
                    "unusual traffic",
                    "request blocked",
                )
            )

            if challenge and not product_context:
                return None, "—", "Costco challenge"

            if not product_context:
                return None, "—", "Costco product context missing"

            # ---------------------------------------------------------
            # Extract structured PRODUCT price only.
            #
            # Do NOT use the first generic "$xx.xx" on the page.
            # ---------------------------------------------------------

            price = "—"

            structured_price_patterns = (
                r'"price"\s*:\s*"?(?:\$)?([\d,]+(?:\.\d{1,2})?)',
                r'"currentPrice"\s*:\s*"?(?:\$)?([\d,]+(?:\.\d{1,2})?)',
                r'"salesPrice"\s*:\s*"?(?:\$)?([\d,]+(?:\.\d{1,2})?)',
                r'"finalPrice"\s*:\s*"?(?:\$)?([\d,]+(?:\.\d{1,2})?)',
            )

            for pattern in structured_price_patterns:
                pm = re.search(pattern, text, re.IGNORECASE)

                if not pm:
                    continue

                try:
                    value = float(pm.group(1).replace(",", ""))
                except (TypeError, ValueError):
                    continue

                # Pokémon TCG products outside this broad range are
                # probably unrelated page/recommendation prices.
                if 2.00 <= value <= 300.00:
                    price = f"${value:.2f}"
                    break

            # ---------------------------------------------------------
            # Strong structured availability signals
            # ---------------------------------------------------------

            structured_in_stock = (
                '"availability":"https://schema.org/instock"',
                '"availability": "https://schema.org/instock"',
                '"availability":"instock"',
                '"availability": "instock"',
                '"availability":"in_stock"',
                '"availability": "in_stock"',
            )

            structured_oos = (
                '"availability":"https://schema.org/outofstock"',
                '"availability": "https://schema.org/outofstock"',
                '"availability":"outofstock"',
                '"availability": "outofstock"',
                '"availability":"out_of_stock"',
                '"availability": "out_of_stock"',
            )

            if any(sig in tl for sig in structured_oos):
                return False, price, "OUT_OF_STOCK"

            if any(sig in tl for sig in structured_in_stock):
                return True, price, "IN_STOCK"

            # ---------------------------------------------------------
            # Costco-specific explicit product state signals
            # ---------------------------------------------------------

            explicit_oos = (
                "product is out of stock",
                "this item is currently unavailable",
                "item is unavailable",
                "currently out of stock",
                "out of stock online",
            )

            if any(sig in tl for sig in explicit_oos):
                return False, price, "OUT_OF_STOCK"

            # ---------------------------------------------------------
            # IMPORTANT:
            #
            # Do NOT use these alone:
            #
            #   add-to-cart
            #   add to cart
            #   warehouse
            #   generic dollar prices
            #
            # They occur in unrelated Costco page components.
            # ---------------------------------------------------------

            return None, price, "Costco availability unknown"

    except asyncio.TimeoutError:
        return None, "—", "Costco timeout"

    except aiohttp.ClientError as e:
        return (
            None,
            "—",
            f"Costco network error: {type(e).__name__}",
        )

    except Exception as e:
        return (
            None,
            "—",
            f"Costco error: {type(e).__name__}",
        )


