    # Special treatment for Pokemon 30th Anniversary products
    name_lower = product["name"].lower()
    is_30th = (
        "30th celebration" in name_lower
        or "30th anniversary" in name_lower
    )

    # Route to right channel
    if is_price_drop:
        hook_key = "price_drops"
    elif "_instore" in retailer:
        hook_key = "in_store"
