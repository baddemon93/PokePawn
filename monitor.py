def normalize_health_retailer(retailer: str) -> str:
    """Keep online and local channels separate where useful."""
    mapping = {
        "pokemon_center": "pokemon_center",
        "target": "target",
        "target_instore": "target",
        "walmart": "walmart",
        "walmart_instore": "walmart_instore",
        "bestbuy": "bestbuy",
        "bestbuy_instore": "bestbuy",
        "costco": "costco",
        "costco_instore": "costco_instore",
        "sams_club": "sams_club",
        "gamestop": "gamestop",
    }
    return mapping.get(retailer, retailer)


def prune_health_stats(now: float | None = None):
    """Discard telemetry older than the rolling four-hour window."""
    global health_stats

    now = now or time.time()
    cutoff = now - HEALTH_WINDOW_SECONDS

    buckets = health_stats.setdefault("buckets", {})

    for key in list(buckets):
        try:
            bucket_ts = float(key)
        except (TypeError, ValueError):
            del buckets[key]
            continue

        if bucket_ts < cutoff:
            del buckets[key]


def save_health_stats(force: bool = False):
    """Persist telemetry without writing on every stock request."""
    global health_last_save

    now = time.time()

    if not force and now - health_last_save < HEALTH_SAVE_INTERVAL:
        return

    prune_health_stats(now)

    HEALTH_STATS_FILE.parent.mkdir(parents=True, exist_ok=True)

    tmp = HEALTH_STATS_FILE.with_suffix(".tmp")

    tmp.write_text(
        json.dumps(
            health_stats,
            indent=2,
            sort_keys=True,
        )
    )

    tmp.replace(HEALTH_STATS_FILE)
    health_last_save = now


def record_health_event(
    retailer: str,
    success: bool | None = None,
    outcome: str = "",
):
    """
    Record one completed retailer observation.

    Outcomes:
        success = trustworthy retailer result
        neutral = expected/unsupported/ambiguous result
        error   = genuine retailer/network failure

    Stored in one-minute buckets to keep telemetry compact.
    """

    now = time.time()

    bucket_ts = int(
        now // HEALTH_BUCKET_SECONDS
    ) * HEALTH_BUCKET_SECONDS

    bucket_key = str(bucket_ts)

    retailer_key = normalize_health_retailer(retailer)

    buckets = health_stats.setdefault("buckets", {})

    bucket = buckets.setdefault(
        bucket_key,
        {
            "success": 0,
            "neutral": 0,
            "errors": 0,
            "retailers": {},
        },
    )

    # Backward compatibility with buckets created before neutral existed.
    bucket.setdefault("success", 0)
    bucket.setdefault("neutral", 0)
    bucket.setdefault("errors", 0)
    bucket.setdefault("retailers", {})

    retailer_bucket = bucket["retailers"].setdefault(
        retailer_key,
        {
            "success": 0,
            "neutral": 0,
            "errors": 0,
        },
    )

    retailer_bucket.setdefault("success", 0)
    retailer_bucket.setdefault("neutral", 0)
    retailer_bucket.setdefault("errors", 0)

    outcome_lower = str(outcome).lower()

    if outcome_lower == "neutral":
        bucket["neutral"] += 1
        retailer_bucket["neutral"] += 1

    elif success is True or outcome_lower == "success":
        bucket["success"] += 1
        retailer_bucket["success"] += 1

    else:
        bucket["errors"] += 1
        retailer_bucket["errors"] += 1

    save_health_stats()


def get_rolling_health() -> dict:
    """Return aggregate telemetry for the rolling four-hour window."""

    now = time.time()
    cutoff = now - HEALTH_WINDOW_SECONDS

    totals = {
        "success": 0,
        "neutral": 0,
        "errors": 0,
        "retailers": {},
    }

    for key, bucket in health_stats.get("buckets", {}).items():
        try:
            bucket_ts = float(key)
        except (TypeError, ValueError):
            continue

        if bucket_ts < cutoff:
            continue

        totals["success"] += int(
            bucket.get("success", 0)
        )

        totals["neutral"] += int(
            bucket.get("neutral", 0)
        )

        totals["errors"] += int(
            bucket.get("errors", 0)
        )

        for retailer, values in bucket.get(
            "retailers",
            {},
        ).items():

            dest = totals["retailers"].setdefault(
                retailer,
                {
                    "success": 0,
                    "neutral": 0,
                    "errors": 0,
                },
            )

            dest["success"] += int(
                values.get("success", 0)
            )

            dest["neutral"] += int(
                values.get("neutral", 0)
            )

            dest["errors"] += int(
                values.get("errors", 0)
            )

    totals["checks"] = (
        totals["success"]
        + totals["neutral"]
        + totals["errors"]
    )

    # Only trustworthy success/failure observations affect reliability.
    totals["rated_checks"] = (
        totals["success"]
        + totals["errors"]
    )

    if totals["rated_checks"]:
        totals["success_rate"] = (
            totals["success"]
            / totals["rated_checks"]
            * 100
        )
    else:
        totals["success_rate"] = None

    return totals

